"""Rebuild the small vision sidecar from committed source-derived grid inputs.

Ordinary builds use the checked-in sidecar. No Steam archive, NumPy, firmware,
walkability bitmap or developer-machine path is required for this rebuild.
"""
from pathlib import Path
import argparse, hashlib, json, math, struct, zlib

ROOT=Path(__file__).resolve().parents[1]
GRID=256
CELL=16
UNKNOWN=-32768
MAGIC=0x31563148

def sha(data):return hashlib.sha256(data).hexdigest()

def encode(height_bytes,trees):
    if len(height_bytes)!=GRID*GRID*2:raise ValueError('Expected 256x256 little-endian int16 ground heights')
    heights=struct.unpack('<65536h',height_bytes)
    bits=bytearray(GRID*GRID//8)
    for tree in trees:
        x,y,r=tree['x_q8'],tree['y_q8'],tree['radius_q8']
        if r!=16*256:raise ValueError('Tree-only radius must exclude movement hull clearance')
        lo_x=max(0,(x-r)//(CELL*256)-1);hi_x=min(GRID-1,(x+r)//(CELL*256)+1)
        lo_y=max(0,(y-r)//(CELL*256)-1);hi_y=min(GRID-1,(y+r)//(CELL*256)+1)
        for cy in range(lo_y,hi_y+1):
            for cx in range(lo_x,hi_x+1):
                dx=(cx*CELL+CELL//2)*256-x;dy=(cy*CELL+CELL//2)*256-y
                if dx*dx+dy*dy<=r*r:
                    i=cy*GRID+cx;bits[i>>3]|=1<<(i&7)
    payload=height_bytes+bits
    crc=zlib.crc32(payload)&0xffffffff
    unknown=sum(h==UNKNOWN for h in heights)
    words=[MAGIC,1,64,4096,GRID,CELL,64,len(height_bytes),64+len(height_bytes),len(bits),len(payload),crc,4,len(trees),unknown,0]
    return struct.pack('<16I',*words)+payload,dict(payload_crc32=crc,tree_records=len(trees),unknown_height_cells=unknown,tree_cells=sum(b.bit_count() for b in bits))

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source',type=Path,default=ROOT/'provenance/vision')
    p.add_argument('--output',type=Path,default=ROOT/'assets/runtime/VISION.H1V')
    p.add_argument('--identity',type=Path,default=ROOT/'platform/vision_asset_identity.h')
    p.add_argument('--check',action='store_true')
    a=p.parse_args();source=a.source.resolve();height=source/'height-grid.i16';trees=source/'trees.json'
    dataset=json.loads(trees.read_text(encoding='utf8'))
    data,stats=encode(height.read_bytes(),dataset['trees'])
    identity=('#ifndef H1_DOTA_VISION_ASSET_IDENTITY_H\n#define H1_DOTA_VISION_ASSET_IDENTITY_H\n'
              '/* Generated by tools/prepare_vision.py; source-derived terrain and trees. */\n'
              f'#define VISION_EXPECTED_PAYLOAD_CRC32 0x{stats["payload_crc32"]:08x}u\n'
              f'#define VISION_EXPECTED_TREE_RECORDS {stats["tree_records"]}u\n'
              f'#define VISION_EXPECTED_UNKNOWN_HEIGHT_CELLS {stats["unknown_height_cells"]}u\n'
              '#endif\n').encode('utf8')
    for target,content in ((a.output,data),(a.identity,identity)):
        target=target.resolve()
        if not target.is_relative_to(ROOT):raise ValueError('Outputs must remain inside this repository')
        if a.check:
            if target.read_bytes()!=content:raise ValueError('Rebuilt bytes differ: '+str(target))
        else:target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(content)
    result=dict(passed=True,sidecar_bytes=len(data),sidecar_sha256=sha(data),height_input_sha256=sha(height.read_bytes()),trees_input_sha256=sha(trees.read_bytes()),**stats)
    print(json.dumps(result))
if __name__=='__main__':main()
