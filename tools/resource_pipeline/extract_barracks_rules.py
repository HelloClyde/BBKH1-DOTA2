"""Derive small dynamic barracks hull patches from the frozen source audit.

Never restores GNV/tree/PHYS-blocked cells or edges. Existing navigation data
and large rendered assets remain unchanged; this emits two new C headers.
"""
from pathlib import Path
import csv, hashlib, json, math
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'private/navigation-v022'

def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def main():
    info=json.loads((SOURCE/'buildings.json').read_bytes())
    rows=sorted(info['static_barracks'],key=lambda r:(0 if 'goodguys' in r['npc_unit'] else 1,('top','mid','bot').index(r['npc_unit'].rsplit('_',1)[1]),0 if '_melee_' in r['npc_unit'] else 1))
    assert len(rows)==12
    base=(np.load(SOURCE/'source-flags.npy')&1)!=0
    base&=~np.load(SOURCE/'tree-blocked.npy')
    static=np.load(SOURCE/'walk.npy')
    assert np.all(static<=base)
    yy,xx=np.mgrid[:256,:256];wx=xx*16+8;wy=yy*16+8
    def hull(row):
        x,y=row['world_xy'];r=row['collision_radius_world']
        return np.maximum(abs(wx-x)-8,0)**2+np.maximum(abs(wy-y)-8,0)**2<=r*r
    owners=np.zeros((256,256),np.uint16)
    for i,row in enumerate(rows):owners[hull(row)]|=1<<i
    # Reconstruct the original pre-barracks edge graph exactly from the
    # independent PHYS collision receipts, before source_passages masking.
    source_edges=np.ones((2,256,256),bool)
    source_edges[0,:,:-1]=~(base[:,:-1]&base[:,1:])
    source_edges[1,:-1,:]=~(base[:-1,:]&base[1:,:])
    with (SOURCE/'physics-edges.csv').open(encoding='ascii') as f:
        for row in csv.DictReader(f):source_edges[int(row['down']),int(row['cell_y']),int(row['cell_x'])]=True
    old_edges=np.stack((np.load(SOURCE/'right.npy'),np.load(SOURCE/'down.npy')))
    assert np.all(source_edges<=old_edges)
    cells=[]
    # Only source-legal cells actually changed by barracks are restored.
    for cell in np.flatnonzero(base&~static):
        y,x=divmod(int(cell),256);tm=fm=0
        for i,row in enumerate(info['dynamic_towers']):
            if hull(row)[y,x]:tm|=1<<i
        for i,row in enumerate(info['dynamic_fillers']):
            if hull(row)[y,x]:fm|=1<<i
        assert owners[y,x]
        cells.append((int(cell),int(owners[y,x]),tm,fm))
    edges=[]
    for down,y,x in zip(*np.where(old_edges&~source_edges)):
        other=(y+int(down),x+int(not down));mask=int(owners[y,x]|owners[other])
        assert mask
        edges.append((int(down)*65536+int(y)*256+int(x),mask))
    edges.sort()
    circles=[]
    for c in info['source_passages']['source_circles']:
        i,= [i for i,r in enumerate(rows) if r['hammer_id']==c['hammer_id']]
        circles.append(i)
    h=['/* Source entity origins / NPC hull audit: private/navigation-v022. */','#ifndef H1_DOTA_BARRACKS_DATA_H','#define H1_DOTA_BARRACKS_DATA_H','static const short dota_barracks_positions[12][2]={']
    h += ['{'+','.join(str(math.floor(v+.5)) for v in r['world_xy'])+'}, /* '+r['npc_unit']+' */' for r in rows]
    h += ['};','#endif']
    (ROOT/'private/generated/dota_barracks_data.h').write_text('\n'.join(h)+'\n',encoding='ascii')
    h=['/* Source legal cells/edges only; generated by extract_barracks_rules.py. */','#ifndef H1_DOTA_BARRACKS_NAV_H','#define H1_DOTA_BARRACKS_NAV_H',f'#define DOTA_BARRACKS_NAV_CELLS {len(cells)}',f'#define DOTA_BARRACKS_NAV_EDGES {len(edges)}','typedef struct {unsigned short cell,owners;unsigned towers,fillers;} DotaBarracksNavCell;','static const DotaBarracksNavCell dota_barracks_nav_cells[DOTA_BARRACKS_NAV_CELLS]={']
    h+=['{'+','.join(map(str,r))+'},' for r in cells]
    h+=['};','typedef struct {unsigned edge;unsigned short owners;} DotaBarracksNavEdge;','static const DotaBarracksNavEdge dota_barracks_nav_edges[DOTA_BARRACKS_NAV_EDGES]={']
    h+=['{'+','.join(map(str,r))+'},' for r in edges]
    h+=['};','static const unsigned char dota_barracks_passage_owners[]={'+','.join(map(str,circles))+'};','#endif']
    (ROOT/'private/generated/dota_barracks_nav.h').write_text('\n'.join(h)+'\n',encoding='ascii')
    print(json.dumps({'cells':len(cells),'edges':len(edges),'source_sha256':{name:digest(SOURCE/name) for name in ('buildings.json','source-flags.npy','tree-blocked.npy','walk.npy','right.npy','down.npy','physics-edges.csv')}}))
if __name__=='__main__':main()
