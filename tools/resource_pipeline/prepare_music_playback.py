"""Bind playback windows to original music events and prepared PCM; no asset rewrite."""
from pathlib import Path
from decimal import Decimal,ROUND_HALF_UP
import array,hashlib,json,math,re,sys

ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'private/audio/assets'
SOURCE=ROOT/'private/audio/source/classic-music.txt'
HEADER=ROOT/'platform/audio_music_windows.h'
ANALYSIS=ROOT/'private/audio/playback/analysis.json'
RATE=32000
THRESHOLD_DB=-45
THRESHOLD=math.floor(32767*10**(THRESHOLD_DB/20))
GUARD=RATE//20 # 50ms around the detected audible body, not an invented Source marker.
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def block(text,name):
    at=text.index(name+' =');start=text.index('{',at);level=0
    for pos in range(start,len(text)):
        if text[pos]=='{':level+=1
        elif text[pos]=='}':
            level-=1
            if not level:return text[start:pos+1]
    raise ValueError(name)
def number(text,key):
    m=re.search(r'\b'+re.escape(key)+r'\s*=\s*([0-9.]+)',text)
    return m.group(1) if m else None
def frame(value):return int((Decimal(value)*RATE).quantize(Decimal('1'),rounding=ROUND_HALF_UP))
def main():
    manifest_path=ASSETS/'manifest.json';pack=ASSETS/'SOUND.H1A';manifest=json.loads(manifest_path.read_text(encoding='utf8'))
    assert manifest['sample_rate']==RATE and sha(pack)==manifest['pack_sha256']
    text=SOURCE.read_text(encoding='utf8');rows=[]
    inputs=[Path(__file__).resolve(),manifest_path,SOURCE,pack]
    event_names=['valve_dota_001.music.ui_main','valve_dota_001.music.laning_01_layer_01','valve_dota_001.music.battle_01']
    for a in manifest['assets'][:5]:
        row={'asset':a['id'],'path':a['path'],'frames':a['frames'],'loop':a['loop'],'first_frame':0,'end_frame':a['frames']}
        if a['id']<3:
            event=block(text,event_names[a['id']]);row['original_event']=event_names[a['id']];row['source_duration_seconds']=number(event,'vsnd_duration')
            slug=hashlib.sha256(a['path'].encode()).hexdigest()[:20];pcm=ASSETS/'converted'/(slug+'.pcm');raw=pcm.read_bytes()
            assert len(raw)==a['frames']*2 and sha(pcm)==a['pcm_sha256'];inputs.append(pcm)
            samples=array.array('h');samples.frombytes(raw)
            if sys.byteorder!='little':samples.byteswap()
            first=next(i for i,s in enumerate(samples) if abs(s)>THRESHOLD)
            end=next(len(samples)-i for i,s in enumerate(reversed(samples)) if abs(s)>THRESHOLD)
            row['amplitude_analysis']={'pcm_sha256':a['pcm_sha256'],'threshold_dbfs':THRESHOLD_DB,'threshold_abs_sample':THRESHOLD,'first_above_threshold':first,'last_above_threshold_exclusive':end,'leading_quiet_seconds':first/RATE,'trailing_quiet_seconds':(len(samples)-end)/RATE}
            start_marker,end_marker=number(event,'start_point'),number(event,'end_point')
            if start_marker is not None and end_marker is not None:
                row.update(window_kind='original_soundevent_markers',first_frame=frame(start_marker),end_frame=frame(end_marker),source_start_point=start_marker,source_end_point=end_marker,source_restart_time=number(event,'restart_time'))
                sync=re.search(r'syncpoints\s*=\s*\[(.*?)\]',event,re.S)
                row['source_syncpoints']=[x for x in re.findall(r'[0-9.]+',sync.group(1))] if sync else []
                row['source_syncpoint_frames']=[frame(x) for x in row['source_syncpoints']]
                assert row['end_frame']-row['first_frame']==frame(row['source_restart_time'])
            else:
                row.update(window_kind='H1_amplitude_trim_adaptation',first_frame=max(0,first-GUARD),end_frame=min(a['frames'],end+GUARD),guard_frames=GUARD,source_has_loop_markers=False)
        else:row['window_kind']='whole_nonloop_source_stinger'
        assert 0<=row['first_frame']<row['end_frame']<=row['frames'];row['playback_seconds']=(row['end_frame']-row['first_frame'])/RATE;rows.append(row)
    lines=['#ifndef DOTA_AUDIO_MUSIC_WINDOWS_H','#define DOTA_AUDIO_MUSIC_WINDOWS_H','#include <stdint.h>','/* Generated by tools/prepare_music_playback.py. End frames are exclusive.',' * Menu/laning: amplitude-derived H1 trim; battle: original soundevent markers.',' * SOUND.H1A bytes, IMA blocks and source PCM are not modified. */','typedef struct {uint32_t first,end;} DotaAudioMusicWindow;','static const DotaAudioMusicWindow audio_music_windows[5]={']
    lines += ['    {%du,%du}, /* asset%d: %s */'%(r['first_frame'],r['end_frame'],r['asset'],r['window_kind']) for r in rows]
    lines += ['};','#endif',''];HEADER.write_text('\n'.join(lines),encoding='utf8')
    report={'passed':True,'data_analysis_only':True,'physical_h1_tested':False,'original_pack_unchanged':True,'pack_sha256':manifest['pack_sha256'],'sample_rate':RATE,'tracks':rows,'zero_gain_groups':[{'group':i,**g} for i,g in enumerate(manifest['groups']) if g.get('volume',1)==0],'generated_header':HEADER.relative_to(ROOT).as_posix(),'generated_header_sha256':sha(HEADER),'source_sha256':{p.relative_to(ROOT).as_posix():sha(p) for p in inputs},'scope':'Read-only original soundevent and exact prepared PCM analysis. Menu/laning trim is explicitly an H1 adaptation, not original loop metadata. Battle markers and syncpoints come directly from the original soundevent. No HDA/WAV/PCM asset is rewritten.'}
    ANALYSIS.parent.mkdir(parents=True,exist_ok=True);ANALYSIS.write_text(json.dumps(report,indent=2)+'\n',encoding='utf8');print(json.dumps({'passed':True,'header_sha256':sha(HEADER),'windows':[(r['asset'],r['first_frame'],r['end_frame'],r['window_kind']) for r in rows]}))
if __name__=='__main__':main()
