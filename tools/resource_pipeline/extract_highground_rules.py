"""Bind the ten high-ground towers and fourteen filler buildings to Steam data."""
from pathlib import Path
import hashlib,json,math,struct
from bake_navigation import ROOT,STEAM,npc_units,native_hulls
from source2_vpk import VpkArchive

def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()

def main():
    out=ROOT/'private/highground';out.mkdir(parents=True,exist_ok=True)
    ep=ROOT/'private/source2/reports/entity-default-parsed.json'
    entities=json.loads(ep.read_text(encoding='utf8'))
    vpk=VpkArchive(STEAM/'pak01_dir.vpk');script='scripts/npc/npc_units.txt'
    raw=vpk.read(script);(out/'npc_units.txt').write_bytes(raw);units=npc_units(raw)
    server=STEAM/'bin/win64/server.dll';hulls=native_hulls(server)
    towers=[];fillers=[]
    def record(e,team,slot):
        n=e['MapUnitName'];u=units[n]
        x,y,z=e['origin'];row=dict(hammer_id=e['hammerUniqueId'],npc=n,team=team,slot=slot,
            origin=e['origin'],angles=e['angles'],model=e['model'],
            world_xy=[math.floor(2048+x/4+.5),math.floor(2048-y/4+.5)],
            unit={k:u[k] for k in ('StatusHealth','ArmorPhysical','AttackDamageMin','AttackDamageMax','AttackRange','AttackRate','AttackAnimationPoint','BaseAttackSpeed','ProjectileSpeed','BoundsHullName','BountyGoldMin') if k in u})
        return row
    for team,faction in enumerate(('goodguys','badguys')):
        for lane in ('top','mid','bot'):
            e,=[e for e in entities if e.get('MapUnitName')==f'npc_dota_{faction}_tower3_{lane}']
            towers.append(record(e,team,len(towers)%5))
        for e in [e for e in entities if e.get('MapUnitName')==f'npc_dota_{faction}_tower4']:
            towers.append(record(e,team,len(towers)%5))
    for e in entities:
        if e.get('classname')=='npc_dota_building':
            fillers.append(record(e,0 if e['MapUnitName']=='npc_dota_goodguys_fillers' else 1,len(fillers)))
    assert len(towers)==10 and len(fillers)==14
    assert [r['team'] for r in towers]==[0]*5+[1]*5
    assert sum(r['team']==0 for r in fillers)==7
    # The map overrides the generic filler model; do not use its script model.
    header=ROOT/'game/highground_data.h'
    text=['/* Generated by extract_highground_rules.py from original entity/NPC data. */',
          '#ifndef H1_HIGHGROUND_DATA_H','#define H1_HIGHGROUND_DATA_H',
          'const DotaPoint dota_high_tower_positions[2][DOTA_HIGH_TOWERS_PER_TEAM]={']
    for team in range(2):text.append('{'+','.join('{%d,%d}'%tuple(r['world_xy']) for r in towers if r['team']==team)+'},')
    text+=['};','const DotaPoint dota_filler_positions[DOTA_FILLER_COUNT]={']
    text.extend('{%d,%d},'%tuple(r['world_xy']) for r in fillers)
    text+=['};','static const unsigned char filler_teams[DOTA_FILLER_COUNT]={'+','.join(str(r['team']) for r in fillers)+'};','#endif']
    header.write_text('\n'.join(text)+'\n',encoding='ascii')
    manifest=dict(complete=True,entities_sha256=sha(ep),source=vpk.identity(script),
                  towers=towers,fillers=fillers,hulls=hulls,
                  header_sha256=sha(header),source_sha256={'tools/extract_highground_rules.py':sha(__file__),'tools/bake_navigation.py':sha(ROOT/'tools/bake_navigation.py')},
                  protection_scope='H1 dependency policy: T3 after both earlier lane towers; T4/fillers after any enemy T3 falls; Ancient after both T4 fall. No native-engine dependency equivalence claimed.',
                  combat_scope='Source scalar HP/armor/range/BAT/AS/windup/projectile, average deterministic damage; filler bounty68. Full backdoor regeneration/fortification not implemented.')
    (out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf8')
    print(json.dumps(dict(towers=len(towers),fillers=len(fillers),header_sha256=sha(header))))

if __name__=='__main__':main()
